"""REPORT.md for one results directory: jobs, held-out scores, OOF, ensembles, comparisons."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from experiments.provenance import read_json
from experiments.spec import Job, Spec
from src.training.common import METRICS, labels_for_indices, score_by_id

FMT = "{:.3f}"


def _row(values: dict | None) -> str:
    if not values:
        return " | ".join([""] * 4)
    return " | ".join(FMT.format(values[m]) for m in [*METRICS, "mean"])


def collect(spec: Spec, jobs: list[Job]) -> dict:
    """Everything the report and the ledger need, read from disk (no recomputation except OOF concat)."""
    results = spec.results_dir
    status = read_json(results / "status.json", {"jobs": {}}).get("jobs", {})
    rows = []
    for job in jobs:
        metrics = read_json(job.run_dir(results) / "metrics.json")
        rows.append({"job": job.name, "arm": job.arm, "seed": job.seed, "fold": job.config.fold,
                     "n_folds": job.config.n_folds, "all_data": job.config.all_data,
                     "epochs": job.config.epochs, "epochs_run": (metrics or {}).get("epochs_run"),
                     "status": status.get(job.name, {}).get("status", "done" if metrics else "pending"),
                     "seconds": status.get(job.name, {}).get("seconds"),
                     "val": (metrics or {}).get("val_mape"), "n_val": (metrics or {}).get("n_val")})
    scores = [read_json(p) for p in sorted((results / "scores").glob("*.json"))] if (results / "scores").exists() else []
    ensembles = [read_json(p) for p in sorted((results / "ensembles").glob("*.json"))] if (results / "ensembles").exists() else []
    compares = [read_json(p) for p in sorted((results / "compare").glob("*.json"))] if (results / "compare").exists() else []
    oof = []
    by_arm: dict[tuple[str, str, str], list[dict]] = {}
    for s in scores:
        if str(s.get("indices", "")).startswith("fold:"):
            by_arm.setdefault((s["arm"], s["which"], s["tta"]), []).append(s)
    for (arm, which, tta), members in by_arm.items():
        n_folds = int(members[0]["indices"].split("/")[1])
        folds = {int(m["indices"][5:].split("/")[0]) for m in members}
        if folds != set(range(n_folds)):
            continue
        frames = [pd.read_csv(results / "scores" / f"{m['job']}_{which}_{tta}.csv") for m in members]
        combined = pd.concat(frames, ignore_index=True)
        if combined["ID"].duplicated().any():
            continue  # several seeds per fold: the ensemble step handles that
        labels = labels_for_indices(spec.cache_dir, spec.labels_csv, combined["idx"].astype(int).tolist())
        oof.append({"arm": arm, "which": which, "tta": tta, "n": int(len(combined)),
                    "per_fold": {m["indices"]: m["mape"]["mean"] for m in sorted(members, key=lambda m: m["indices"])},
                    "mape": score_by_id(combined, labels, expected_ids=labels.ID)})
    return {"jobs": rows, "scores": scores, "oof": oof, "ensembles": ensembles, "compares": compares}


def write_report(spec: Spec, jobs: list[Job]) -> Path:
    data = collect(spec, jobs)
    plan = read_json(spec.results_dir / "plan.json", {})
    lines = [f"# {spec.name}", "",
             f"Spec `{spec.path.name}`; results `{spec.results_dir}`; git {plan.get('git', {}).get('commit', '?')[:12]}"
             f"{' (dirty)' if plan.get('git', {}).get('dirty') else ''}; generated by `python -m experiments.run report`.",
             "", "## Jobs", "",
             "| job | arm | seed | fold | epochs | status | s | val CD | val CV | val HEX | val mean | n_val |",
             "|---|---|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|"]
    for r in data["jobs"]:
        fold = "" if r["fold"] < 0 else f"{r['fold']}/{r['n_folds']}"
        epochs = f"{r['epochs_run'] or ''}/{r['epochs']}"
        lines.append(f"| {r['job']} | {r['arm']} | {r['seed']} | {fold} | {epochs} | {r['status']} | "
                     f"{'' if r['seconds'] is None else int(r['seconds'])} | {_row(r['val'])} | {r['n_val'] or ''} |")
    if data["scores"]:
        lines += ["", "## Held-out scores (checkpoint + TTA)", "",
                  "| job | indices | which | epoch | tta | n | CD | CV | HEX | mean |", "|---|---|---|---:|---|---:|---:|---:|---:|---:|"]
        for s in sorted(data["scores"], key=lambda s: (s["arm"], s["job"], s["which"], s["tta"])):
            lines.append(f"| {s['job']} | {s['indices']} | {s['which']} | {s['epoch']} | {s['tta']} | {s['n']} | {_row(s['mape'])} |")
    if data["oof"]:
        lines += ["", "## Out-of-fold over all folds (each image scored by the model that did not train on it)", "",
                  "| arm | which | tta | n | CD | CV | HEX | mean | per fold |", "|---|---|---|---:|---:|---:|---:|---:|---|"]
        for o in data["oof"]:
            per = " ".join(FMT.format(v) for v in o["per_fold"].values())
            lines.append(f"| {o['arm']} | {o['which']} | {o['tta']} | {o['n']} | {_row(o['mape'])} | {per} |")
    if data["ensembles"]:
        lines += ["", "## Ensembles (weighted geometric mean)", "",
                  "| ensemble | members | n | CD | CV | HEX | mean |", "|---|---|---:|---:|---:|---:|---:|"]
        for e in data["ensembles"]:
            lines.append(f"| {e['ensemble']} | {json.dumps(e['members'])} | {e['n']} | {_row(e['mape'])} |")
    if data["compares"]:
        lines += ["", "## Paired comparisons (slide-clustered bootstrap; negative favours the candidate)", "",
                  "| candidate | reference | n | candidate mean | reference mean | delta | 95% CI |", "|---|---|---:|---:|---:|---:|---|"]
        for c in data["compares"]:
            lo, hi = c["delta_ci95_slide_boot"]
            lines.append(f"| {c['candidate']} | {c['reference']} | {c['n']} | {FMT.format(c['candidate_mape']['mean'])} | "
                         f"{FMT.format(c['reference_mape']['mean'])} | {c['delta_mean']:+.3f} | [{lo:+.3f}, {hi:+.3f}] |")
    lines += ["", "Selection rule: judge candidates on out-of-fold scores, not on the 892 val split; a gain under 0.10 "
              "on the mean is not visible on 100 hidden images (docs/RESEARCHER_GUIDE.md)."]
    out = spec.results_dir / "REPORT.md"
    out.write_text("\n".join(lines) + "\n")
    return out
